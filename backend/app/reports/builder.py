"""Cable-N report packaging.

Report = Cable-N cover + contents + summary pages (built here) followed by
the ORIGINAL engine report (detailed variant), unchanged, with a traceability
stamp (report number, revision, input hash, page x/y) added to every page.
No signatures, approvals or certification marks are generated. Nothing is stored:
the caller receives the bytes and the temporary directory is removed.
"""
from __future__ import annotations

import io
import os
import shutil
import tempfile
from datetime import datetime

from fpdf import FPDF
from pypdf import PdfReader, PdfWriter

from ..core.config import get_settings
from ..engine import mode1, mode2, mode3, mode4
from ..engine.runtime import latin1

RED = (206, 27, 40)
INK = (33, 33, 33)
MUTED = (111, 115, 120)
LINE = (234, 234, 234)

MODE_TITLES = {
    'single_feeder': 'Single Feeder Cable Sizing',
    'batch': 'Batch Cable Schedule',
    'current_rating': 'Current-Rating Verification',
    'advanced_mvhv': 'IEC 60287 / 60949 MV-HV Analysis',
}
REVIEW_TEXT = {
    'unreviewed': 'NOT REVIEWED - generated by the public Cable-N website; independent engineering '
                  'verification is required',
}
NOTICE = ('Engineering verification notice: results are produced by a deterministic calculation '
          'engine from the inputs listed. Passing numerical checks is not design approval. This '
          'report must be checked by a qualified electrical engineer and verified against the '
          'applicable standards and local authority requirements before use. It does not certify '
          'compliance or electrical safety.')


class _Doc(FPDF):
    def __init__(self, meta):
        super().__init__()
        self.meta = meta
        self.set_auto_page_break(True, margin=20)
        self.set_margins(15, 15, 15)

    def multi_cell(self, *args, **kwargs):
        # cursor to the left margin of the next line (classic behaviour)
        if 'ln' not in kwargs:
            from fpdf.enums import XPos, YPos
            kwargs.setdefault('new_x', XPos.LMARGIN)
            kwargs.setdefault('new_y', YPos.NEXT)
        return super().multi_cell(*args, **kwargs)

    def header(self):
        if self.page_no() == 1:
            return
        self.set_font('helvetica', 'B', 9)
        self.set_text_color(*RED)
        self.cell(0, 6, 'Cable-N', 0, 0, 'L')
        self.set_text_color(*MUTED)
        self.set_font('helvetica', '', 8)
        self.cell(0, 6, latin1(f"{self.meta['number']}  Rev {self.meta['revision']}"), 0, 1, 'R')
        self.set_draw_color(*RED)
        self.set_line_width(0.6)
        self.line(15, self.get_y(), 195, self.get_y())
        self.ln(4)
        self.set_text_color(*INK)


def _h(pdf, text, size=13):
    pdf.set_font('helvetica', 'B', size)
    pdf.set_text_color(*INK)
    pdf.cell(0, 8, latin1(text), 0, 1)
    pdf.set_font('helvetica', '', 9)


def _kv(pdf, rows, w1=60):
    pdf.set_font('helvetica', '', 9)
    for k, v in rows:
        pdf.set_text_color(*MUTED)
        pdf.cell(w1, 6, latin1(k), 'B', 0)
        pdf.set_text_color(*INK)
        pdf.multi_cell(0, 6, latin1('-' if v in (None, '') else v), 'B', 'L')
    pdf.ln(2)


def _table(pdf, heads, rows, widths):
    pdf.set_font('helvetica', 'B', 8)
    pdf.set_fill_color(253, 236, 238)
    for h, w in zip(heads, widths):
        pdf.cell(w, 6, latin1(h), 1, 0, 'C', True)
    pdf.ln()
    pdf.set_font('helvetica', '', 8)
    for r in rows:
        if pdf.get_y() > 270:
            pdf.add_page()
        for v, w in zip(r, widths):
            if v == 'PASS':
                pdf.set_text_color(30, 122, 52)
            elif v in ('FAIL', 'OVERLOAD', 'REVIEW'):
                pdf.set_text_color(168, 18, 30)
            pdf.cell(w, 6, latin1(v), 1, 0, 'C')
            pdf.set_text_color(*INK)
        pdf.ln()
    pdf.ln(2)


def _f(v, n=2):
    return '-' if v is None else f'{v:.{n}f}'


def _summary(pdf, mode, inputs, result):
    _h(pdf, '2. Summary of Results')
    if mode == 'single_feeder':
        _kv(pdf, [('Design current Ib', f"{result['design_current']:.2f} A"),
                  ('Cable table', result['table_key']),
                  ('Arrangement', result['installation_description']),
                  ('Short-circuit check', 'enabled' if result['has_sc'] else 'not requested')])
        if result['single']:
            s = result['single']; r = s['recommended']
            _h(pdf, 'Recommended single circuit', 11)
            _kv(pdf, [('Circuit', s['circuit']), ('Derated capacity Iz', f"{r['derated_current']:.1f} A"),
                      ('Utilisation Ib/Iz', f"{r['utilisation']:.0f} %"),
                      ('Voltage drop', f"{r['voltage_drop']:.2f} %"),
                      ('Short-circuit withstand', f"{r['short_circuit']:.2f} kA"
                       + (f" vs {r['sc_required']:.2f} kA -> {r['sc_status']}" if r['sc_status'] else '')),
                      ('Governing constraint', s['governing']), ('Derating chain', s['chain'])])
        if result['best_by_spacing']:
            _h(pdf, 'Parallel-run options (best per spacing)', 11)
            _table(pdf, ['Spacing', 'Runs', 'Size mm2', 'Iz A', 'Util %', 'VD %', 'SC'],
                   [[b['spacing'], str(b['runs']), b['size'], _f(b['derated_current'], 1),
                     _f(b['utilisation'], 0), _f(b['voltage_drop']), b['sc_status'] or '-']
                    for b in result['best_by_spacing']], [26, 16, 24, 26, 22, 22, 22])
        if result['checks']:
            _h(pdf, 'Engineering checks', 11)
            _table(pdf, ['Check', 'Status', 'Detail'],
                   [[c['name'], c['status'], c['detail']] for c in result['checks']], [55, 30, 95])
    elif mode == 'batch':
        sm = result['summary']
        _kv(pdf, [('Construction', result['construction']), ('Arrangement', result['installation_description']),
                  ('Feeders', f"{sm['total']} entered, {sm['calculated']} calculated, {sm['invalid']} invalid"),
                  ('No solution', str(sm['no_solution'])), ('Short-circuit fail', str(sm['sc_fail'])),
                  ('Parallel-run fallback', str(sm['parallel_fallback']))])
        _table(pdf, ['Tag', 'Ib A', 'Runs', 'Size', 'Iz A', 'Util %', 'VD %', 'Status'],
               [[r['tag'], _f(r['ib'], 1), str(r['rec']['runs']) if r['rec'] else '-',
                 r['rec']['size'] if r['rec'] else '-', _f(r['rec']['derated_current'], 1) if r['rec'] else '-',
                 _f(r['rec']['utilisation'], 0) if r['rec'] else '-', _f(r['rec']['voltage_drop']) if r['rec'] else '-',
                 r['status']] for r in result['rows']], [26, 20, 14, 20, 24, 20, 20, 36])
        if result['invalid_rows']:
            _h(pdf, 'Rows not calculated (invalid input)', 11)
            for r in result['invalid_rows']:
                pdf.multi_cell(0, 5, latin1(f"{r['tag']}: {'; '.join(r['errors'])}"))
    elif mode == 'current_rating':
        sm = result['summary']
        _kv(pdf, [('Positions rated', str(sm['positions'])), ('With load entered', str(sm['loaded'])),
                  ('Overloaded', str(sm['overload'])), ('Lowest rating', f"{sm['min_rating']:.1f} A"),
                  ('Effective rho', f"{result['rho_used']} K.m/W"),
                  ('Inter-bank factor', f"{result['inter']:.2f} ({result['inter_note']})")])
        _table(pdf, ['Position', 'Config', 'Rating A', 'Load A', 'Util %', 'Status'],
               [[p['pos'], p['config_label'], _f(p['iz'], 1), _f(p.get('load'), 1),
                 _f(p.get('util'), 0), p.get('status') or '-'] for p in result['positions']],
               [28, 40, 28, 28, 24, 32])
    elif mode == 'advanced_mvhv':
        g = result['governing']
        _kv(pdf, [('Standard basis', result['standard']['name']),
                  ('Installation', f"{result['installation']} ({result['formation']})"),
                  ('Ambient', f"{result['tg']} C"),
                  ('Governing cable', f"{g['tag']} {g['desig']} - {g['I']:.1f} A")])
        _table(pdf, ['Position', 'Cable', 'T4', 'dT int K', 'Rating A', 'Tcond C'],
               [[p['tag'], p['desig'], _f(p['T4'], 3), _f(p['dt_int']), _f(p['I'], 1), _f(p['theta_op'], 1)]
                for p in result['placed']], [30, 26, 26, 28, 30, 30])
    ws = result.get('warnings') or []
    if ws:
        _h(pdf, 'Engineering warnings', 11)
        pdf.set_text_color(154, 91, 0)
        for w in ws:
            pdf.multi_cell(0, 5, latin1('- ' + w))
        pdf.set_text_color(*INK)


def _cover(meta, mode, inputs, result, has_detail, pages=None):
    """pages: sheet numbers from a first pass ({'summary', 'reviews', 'end'})."""
    pages = pages or {}
    marks = {}
    pdf = _Doc(meta)
    pdf.add_page()
    logo = get_settings().LOGO_PATH
    if os.path.exists(logo):
        try:
            pdf.image(logo, x=15, y=14, h=14)
        except Exception:
            pass
    pdf.set_xy(15, 40)
    pdf.set_font('helvetica', 'B', 26)
    pdf.set_text_color(*RED)
    pdf.cell(0, 12, 'Cable-N', 0, 1)
    pdf.set_font('helvetica', '', 10)
    pdf.set_text_color(*MUTED)
    pdf.cell(0, 6, 'Cable Sizing & Engineering Intelligence', 0, 1)
    pdf.ln(8)
    pdf.set_font('helvetica', 'B', 18)
    pdf.set_text_color(*INK)
    pdf.multi_cell(0, 9, latin1(MODE_TITLES.get(mode, mode)))
    pdf.set_font('helvetica', '', 12)
    pdf.multi_cell(0, 7, latin1(meta['title']))
    pdf.ln(4)
    _kv(pdf, [('Report number', meta['number']), ('Revision', str(meta['revision'])),
              ('Project', meta.get('project_name')), ('Project number', meta.get('project_number')),
              ('Client', meta.get('client')), ('Site', meta.get('site')),
              ('Scenario', meta.get('scenario')),
              ('Prepared by', meta.get('engineer')), ('Checked by', meta.get('reviewer') or '-'),
              ('Report generated', meta['generated']),
              ('Calculation engine', meta['engine_version']),
              ('Input snapshot hash', meta['input_hash'][:32] + '...'),
              ('Review status', REVIEW_TEXT.get(meta['status'], meta['status']))])
    pdf.set_fill_color(253, 236, 238)
    pdf.set_text_color(168, 18, 30)
    pdf.set_font('helvetica', '', 8.5)
    pdf.multi_cell(0, 4.6, latin1(NOTICE), 0, 'L', True)
    pdf.set_text_color(*INK)

    pdf.add_page()
    _h(pdf, '1. Contents')
    pdf.set_font('helvetica', '', 10)
    def pg(k):
        return str(pages[k]) if k in pages else '-'
    toc = [('1. Contents', '2'), ('2. Summary of results, checks and warnings', pg('summary'))]
    if meta.get('reviews'):
        toc.append(('Appendix A - review history', pg('reviews')))
    if has_detail:
        toc.append(('3. Detailed calculation (original engine report: inputs, derating chains,',
                    str(pages['end'] + 1) if 'end' in pages else '-'))
        toc.append(('    all options, diagrams, references)', ''))
    for t, p_ in toc:
        pdf.cell(160, 6, latin1(t), 0, 0)
        pdf.cell(0, 6, latin1(p_), 0, 1, 'R')
    pdf.set_font('helvetica', 'I', 8)
    pdf.set_text_color(*MUTED)
    pdf.multi_cell(0, 4, 'Sheet numbers refer to the "sheet x of y" stamp at the foot of every page. '
                         'The detailed section keeps the original engine report layout and its own page numbering.')
    pdf.set_text_color(*INK)
    pdf.ln(4)
    marks['summary'] = pdf.page_no()
    _summary(pdf, mode, inputs, result)
    if meta.get('reviews'):
        if pdf.get_y() > 230:
            pdf.add_page()
        marks['reviews'] = pdf.page_no()
        _h(pdf, 'Appendix A - review history', 11)
        _table(pdf, ['Date', 'Rev', 'Action', 'By', 'Comment'],
               [[r['date'], str(r['rev']), r['action'], r['by'], (r['comment'] or '')[:60]]
                for r in meta['reviews']], [28, 12, 24, 36, 80])
    marks['end'] = pdf.page_no()
    if not pages:
        return marks
    return bytes(pdf.output())


def _stamp(writer: PdfWriter, meta):
    total = len(writer.pages)
    for i, page in enumerate(writer.pages, 1):
        w = float(page.mediabox.width); h = float(page.mediabox.height)
        s = FPDF(unit='pt', format=(w, h))
        s.set_auto_page_break(False)
        s.add_page()
        s.set_font('helvetica', '', 6.5)
        s.set_text_color(120, 120, 120)
        s.set_xy(20, h - 14)
        s.cell(w - 40, 8, latin1(f"Cable-N  |  {meta['number']} Rev {meta['revision']}  |  input "
                                 f"{meta['input_hash'][:12]}  |  {meta['engine_version']}  |  sheet {i} of {total}"),
               0, 0, 'C')
        overlay = PdfReader(io.BytesIO(bytes(s.output()))).pages[0]
        page.merge_page(overlay)


def build_report(meta: dict, mode: str, inputs: dict, result: dict, kind: str = 'detailed') -> bytes:
    tmp = tempfile.mkdtemp(prefix='cablen-rpt-')
    try:
        return _build(meta, mode, inputs, result, kind, tmp)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def _build(meta, mode, inputs, result, kind, tmp):
    detail_path = None
    if kind == 'detailed':
        proj = {'name': meta.get('project_name') or meta['title'], 'client': meta.get('client') or '',
                'ref': meta['number']}
        if mode == 'single_feeder':
            detail_path = mode1.generate_pdf(inputs, result, tmp, proj)
        elif mode == 'batch':
            detail_path = mode2.generate_pdf(inputs['common'], inputs['feeders'], result['arrangement'], tmp, proj)
        elif mode == 'current_rating':
            detail_path = mode3.generate_pdf(inputs, tmp, proj)
        elif mode == 'advanced_mvhv':
            detail_path = mode4.generate_pdf(inputs, tmp, proj)
    marks = _cover(meta, mode, inputs, result, detail_path is not None)
    cover = _cover(meta, mode, inputs, result, detail_path is not None, pages=marks)
    writer = PdfWriter()
    for p in PdfReader(io.BytesIO(cover)).pages:
        writer.add_page(p)
    if detail_path:
        for p in PdfReader(detail_path).pages:
            writer.add_page(p)
    _stamp(writer, meta)
    writer.add_metadata({'/Title': latin1(f"{meta['number']} {meta['title']}"), '/Producer': 'Cable-N',
                         '/Subject': MODE_TITLES.get(mode, mode)})
    out = io.BytesIO()
    writer.write(out)
    return out.getvalue()


