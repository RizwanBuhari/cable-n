"""Builds app/engine/legacy_engine.py from the read-only original.

The original CLI program (reference/original_engine/cable_sizing_FINAL.py) is
the authoritative calculation engine. Cable-N imports it as a module, so every
table, constant and formula executes exactly as written. The ONLY changes are
the I/O patches listed in PATCHES below: the original copies finished PDFs to a
sandbox path ('/mnt/user-data/outputs'), which on Windows would create folders
at the root of the system drive. Each patch is a literal text replacement, and
tests/test_engine_parity.py proves that every other top-level function and
constant is AST-identical to the original.

Run:  python -m app.engine.build_legacy
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
ORIGINAL = ROOT / 'reference' / 'original_engine' / 'cable_sizing_FINAL.py'
TARGET = Path(__file__).with_name('legacy_engine.py')

HEADER = (
    '# AUTO-GENERATED by app/engine/build_legacy.py - DO NOT EDIT.\n'
    '# Verbatim copy of reference/original_engine/cable_sizing_FINAL.py with the\n'
    '# I/O-only patches marked "CABLE-N PATCH". See docs/ENGINE_MAPPING.md.\n'
)

# (function name, original text, replacement text)
PATCHES = [
    ('generate_batch_pdf',
     "    import shutil\n"
     "    os.makedirs('/mnt/user-data/outputs', exist_ok=True)\n"
     "    shutil.copy(filename, f'/mnt/user-data/outputs/{filename}')\n"
     "    print(f\"\\nCable schedule PDF generated: /mnt/user-data/outputs/{filename}\")\n",
     "    # CABLE-N PATCH: no sandbox copy; output() is redirected by the adapter\n"
     "    print(f\"\\nCable schedule PDF generated: {filename}\")\n"),
    ('generate_mode4_pdf',
     "    import shutil, os as _os\n"
     "    _os.makedirs('/mnt/user-data/outputs', exist_ok=True)\n"
     "    shutil.copy(fn, f'/mnt/user-data/outputs/{fn}')\n"
     "    print(f\"\\nPDF: /mnt/user-data/outputs/{fn}\")\n"
     "    globals()['_LAST_MODE4_PDF'] = f'/mnt/user-data/outputs/{fn}'\n",
     "    # CABLE-N PATCH: no sandbox copy; output() is redirected by the adapter\n"
     "    print(f\"\\nPDF: {fn}\")\n"
     "    globals()['_LAST_MODE4_PDF'] = fn\n"),
]
PATCHED_FUNCTIONS = {p[0] for p in PATCHES}


def build_source() -> str:
    src = ORIGINAL.read_text(encoding='utf-8')
    for name, old, new in PATCHES:
        if src.count(old) != 1:
            raise RuntimeError(f'patch for {name} does not apply cleanly')
        src = src.replace(old, new)
    return HEADER + src


def main():
    TARGET.write_text(build_source(), encoding='utf-8')
    print(f'wrote {TARGET}')


if __name__ == '__main__':
    main()
